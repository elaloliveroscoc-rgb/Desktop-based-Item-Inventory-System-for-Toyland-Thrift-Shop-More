public void loadCartTable() {
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tableCart.getModel();
    model.setRowCount(0);

    String query = "SELECT * FROM cart";
    double grandTotal = 0.0;
    int totalItems = 0;

    try (java.sql.Connection conn = none.shopinventorysystem.DBConnection.getConnection();
         java.sql.PreparedStatement pstmt = conn.prepareStatement(query);
         java.sql.ResultSet rs = pstmt.executeQuery()) {

        int counter = 1;
        while (rs.next()) {
            int qty = rs.getInt("quantity");
            double subtotal = rs.getDouble("subtotal");

            grandTotal += subtotal;
            totalItems += qty;

            Object[] row = new Object[] {
                counter++,
                rs.getString("item_name"),
                qty,
                rs.getString("size"),
                "₱" + rs.getDouble("price"),
                "₱" + String.format("%.2f", subtotal)
            };
            model.addRow(row);
        } // Closing bracket para sa while loop

       // I-update ang summary labels
        if (lblTotalItems != null) lblTotalItems.setText("Total Items: " + totalItems);
        if (lblGrandTotal != null) lblGrandTotal.setText("Grand Total: ₱" + String.format("%.2f", grandTotal));
        
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error loading cart data: " + e.getMessage());
    }
    }

