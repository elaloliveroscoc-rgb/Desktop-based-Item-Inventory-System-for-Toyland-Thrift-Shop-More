    private void btnCheckoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCheckoutActionPerformed
        // TODO add your handling code here:
String customerName = txtCustomerName.getText().trim();
    if (customerName.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter the Customer Name before proceeding to checkout.", "Validation Error", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tableCart.getModel();
    if (model.getRowCount() == 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Your Cart is empty!", "Cart Empty", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 1. Calculate Grand Total ug Simple Receipt
    double totalCartAmount = 0.0;
    int totalItemsQty = 0;
    StringBuilder itemsSummary = new StringBuilder();
    StringBuilder receiptDetails = new StringBuilder();

    receiptDetails.append("--- TOYLAND RECEIPT ---\n");
    receiptDetails.append("Customer: ").append(customerName).append("\n");
    receiptDetails.append("Date: ").append(java.time.LocalDate.now().toString()).append("\n");
    receiptDetails.append("-----------------------\n");

    for (int i = 0; i < model.getRowCount(); i++) {
        String itemName = model.getValueAt(i, 1).toString();
        int qty = Integer.parseInt(model.getValueAt(i, 2).toString());
        String totalStr = model.getValueAt(i, 5).toString().replace("₱", "").trim();
        double subtotal = Double.parseDouble(totalStr);

        totalCartAmount += subtotal;
        totalItemsQty += qty;

        if (i > 0) itemsSummary.append(", ");
        itemsSummary.append(itemName).append(" (x").append(qty).append(")");

        // Simple compact line
        receiptDetails.append(itemName).append(" x").append(qty).append(" - ₱").append(String.format("%.2f", subtotal)).append("\n");
    }

    receiptDetails.append("-----------------------\n");
    receiptDetails.append("Total: ₱").append(String.format("%.2f", totalCartAmount)).append("\n");

    // 2. Input Payment
    String paidInput = javax.swing.JOptionPane.showInputDialog(this, "Grand Total: ₱" + String.format("%.2f", totalCartAmount) + "\nAmount Paid:", totalCartAmount);
    if (paidInput == null || paidInput.trim().isEmpty()) return;

    double amountPaid = 0.0;
    try {
        amountPaid = Double.parseDouble(paidInput.trim());
        if (amountPaid < totalCartAmount) {
            javax.swing.JOptionPane.showMessageDialog(this, "Insufficient payment!", "Payment Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Invalid amount format.", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    double changeAmount = amountPaid - totalCartAmount;

    receiptDetails.append("Paid: ₱").append(String.format("%.2f", amountPaid)).append("\n");
    receiptDetails.append("Change: ₱").append(String.format("%.2f", changeAmount)).append("\n");
    receiptDetails.append("-----------------------\n");
    receiptDetails.append("Thank you");

    // 3. Save Transaction
    String sqlTransaction = "INSERT INTO sales_transactions (customer_name, item_name, quantity, total_amount, amount_paid, change_amount, transaction_date) VALUES (?, ?, ?, ?, ?, ?, NOW())";
    String sqlClearCart = "DELETE FROM cart";

    try (java.sql.Connection conn = none.shopinventorysystem.DBConnection.getConnection()) {
        conn.setAutoCommit(false);

        try (java.sql.PreparedStatement pstmtTx = conn.prepareStatement(sqlTransaction)) {
            pstmtTx.setString(1, customerName);
            pstmtTx.setString(2, itemsSummary.toString());
            pstmtTx.setInt(3, totalItemsQty);
            pstmtTx.setDouble(4, totalCartAmount);
            pstmtTx.setDouble(5, amountPaid);
            pstmtTx.setDouble(6, changeAmount);
            pstmtTx.executeUpdate();
        }

        try (java.sql.PreparedStatement pstmtClear = conn.prepareStatement(sqlClearCart)) {
            pstmtClear.executeUpdate();
        }

        conn.commit();

        // 4. Custom JDialog Window (WALAY BLUE CIRCLE ICON / WALAY JOPTIONPANE)
        javax.swing.JTextArea textArea = new javax.swing.JTextArea(receiptDetails.toString());
        textArea.setFont(new java.awt.Font("Monospaced", java.awt.Font.BOLD, 16));
        textArea.setEditable(false);
        textArea.setBackground(java.awt.Color.WHITE);

        javax.swing.JScrollPane scrollPane = new javax.swing.JScrollPane(textArea);

        javax.swing.JDialog receiptDialog = new javax.swing.JDialog(this, "Receipt", true);
        receiptDialog.setLayout(new java.awt.BorderLayout(10, 10));
        receiptDialog.add(scrollPane, java.awt.BorderLayout.CENTER);

        javax.swing.JButton btnClose = new javax.swing.JButton("OK");
        btnClose.setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 14));
        btnClose.setPreferredSize(new java.awt.Dimension(100, 35));
        btnClose.addActionListener(e -> receiptDialog.dispose());

        javax.swing.JPanel buttonPanel = new javax.swing.JPanel();
        buttonPanel.add(btnClose);
        receiptDialog.add(buttonPanel, java.awt.BorderLayout.SOUTH);

// Kasarangan ra nga Size Display (Dili Full Screen)
receiptDialog.setSize(450, 400); // 450px width, 400px height
receiptDialog.setLocationRelativeTo(this); // I-center sa ibabaw sa Cart window
receiptDialog.setVisible(true);

        // Reset Cart View
        model.setRowCount(0);
        txtCustomerName.setText("");
        if (lblTotalItems != null) lblTotalItems.setText("Total Items: 0");
        if (lblGrandTotal != null) lblGrandTotal.setText("Grand Total: ₱0.00");

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error sa Checkout: " + e.getMessage(), "Checkout Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnCheckoutActionPerformed

