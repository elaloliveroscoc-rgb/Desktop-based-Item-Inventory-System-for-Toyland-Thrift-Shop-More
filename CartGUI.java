    private void btnRemoveItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveItemActionPerformed
        // TODO add your handling code here:
      int selectedRow = tableCart.getSelectedRow();
    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select an item from the cart to remove.", "Selection Required", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    String itemName = tableCart.getValueAt(selectedRow, 1).toString();
    String deleteSql = "DELETE FROM cart WHERE item_name = ? LIMIT 1";

    try (java.sql.Connection conn = none.shopinventorysystem.DBConnection.getConnection();
         java.sql.PreparedStatement pstmt = conn.prepareStatement(deleteSql)) {

        pstmt.setString(1, itemName);
        pstmt.executeUpdate();

        loadCartTable(); // Refresh UI
        javax.swing.JOptionPane.showMessageDialog(this, itemName + " removed from cart.");

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error removing item: " + e.getMessage());
    }
    }//GEN-LAST:event_btnRemoveItemActionPerformed

