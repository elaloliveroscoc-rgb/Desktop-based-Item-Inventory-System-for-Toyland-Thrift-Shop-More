    private void searchAndSelectRow() {
    String query = txtSearch.getText().trim();
    
    if (query.isEmpty()) {
        table.clearSelection();
        clearInputs();
        return;
    }

    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) table.getModel();
    boolean found = false;

    for (int i = 0; i < model.getRowCount(); i++) {
        Object numObj = model.getValueAt(i, 0); 
        
        if (numObj != null && numObj.toString().trim().equalsIgnoreCase(query)) {
            table.setRowSelectionInterval(i, i);
            table.scrollRectToVisible(table.getCellRect(i, 0, true));
            
            txtItem.setText(model.getValueAt(i, 1) != null ? model.getValueAt(i, 1).toString() : "");
            txtQty.setText(model.getValueAt(i, 2) != null ? model.getValueAt(i, 2).toString() : "");
            txtSize.setText(model.getValueAt(i, 3) != null ? model.getValueAt(i, 3).toString() : "");
            txtWeight.setText(model.getValueAt(i, 4) != null ? model.getValueAt(i, 4).toString() : "");
            txtPrice.setText(model.getValueAt(i, 5) != null ? model.getValueAt(i, 5).toString() : "");
            if (cbStatus != null && model.getValueAt(i, 6) != null) {
                cbStatus.setSelectedItem(model.getValueAt(i, 6).toString());
            }
            // txtDateSold line removed to fix IndexOutOfBoundsException

            found = true;
            break;
        }
    }

    if (!found) {
        table.clearSelection();
        clearInputs();
    }
    }
    
   private void highlightSidebarButton(javax.swing.JButton activeButton) {
 javax.swing.JButton[] sidebarButtons = {
        btnInventory, btnCart, btnTransaction, btnAvailable, btnReserved, btnReports, btnLowStock, btnLogout
    };

    java.awt.Color inactiveBg = new java.awt.Color(35, 45, 65);
    java.awt.Color activeBg = new java.awt.Color(30, 144, 255);

    for (javax.swing.JButton btn : sidebarButtons) {
        if (btn != null) {
            btn.setOpaque(true);
            btn.setBorderPainted(false);
            btn.setFocusPainted(false);
            btn.setBackground(inactiveBg);
            btn.setForeground(java.awt.Color.WHITE);
        }
    }

    if (activeButton != null) {
        activeButton.setBackground(activeBg);
        activeButton.setForeground(java.awt.Color.WHITE);
    }
   }
    
