    private void cartactionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cartactionPerformed
        // TODO add your handling code here:                              
int selectedRow = table.getSelectedRow();
    
    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select an item from the table to Add to Cart.", "Selection Required", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    int modelRow = table.convertRowIndexToModel(selectedRow);
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) table.getModel();

    String itemName = model.getValueAt(modelRow, 1).toString();
    int currentStock = Integer.parseInt(model.getValueAt(modelRow, 2).toString());
    String size = model.getValueAt(modelRow, 3) != null ? model.getValueAt(modelRow, 3).toString() : "";
    String weight = model.getValueAt(modelRow, 4) != null ? model.getValueAt(modelRow, 4).toString() : "";
    String priceStr = model.getValueAt(modelRow, 5).toString().replace("₱", "").trim();
    double price = Double.parseDouble(priceStr);

    if (currentStock <= 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "The item " + itemName + " is OUT OF STOCK!", "Stock Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 1. Pangutana kon pila ka quantity ang idadag sa Cart
    String inputQtyStr = javax.swing.JOptionPane.showInputDialog(this,"How many quantities would you like to add to the Cart for: " + itemName + "?", "1");
    if (inputQtyStr == null || inputQtyStr.trim().isEmpty()) return;

    try {
        int buyQty = Integer.parseInt(inputQtyStr.trim());
        if (buyQty <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid quantity (greater than 0).", "Quantity Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (buyQty > currentStock) {
            javax.swing.JOptionPane.showMessageDialog(this, "Invalid! The available stock is only " + currentStock + ".", "Stock Exceeded", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        double subtotal = price * buyQty;

        // SQL Queries with Exact Parameter Matching
        String insertCartSql = "INSERT INTO cart (item_name, quantity, size, weight, price, subtotal) VALUES (?, ?, ?, ?, ?, ?)";
        String updateInventorySql = "UPDATE inventory SET quantity = quantity - ? WHERE item_name = ? AND size = ? AND weight = ? AND quantity >= ? LIMIT 1";
        String updateAvailableSql = "UPDATE available SET quantity = quantity - ? WHERE item_name = ? AND size = ? AND weight = ? AND quantity >= ? LIMIT 1";

        try (java.sql.Connection conn = DBConnection.getConnection()) {
            conn.setAutoCommit(false); // Single Transaction Scope

            // A. Save to Cart Table
            try (java.sql.PreparedStatement pstmt = conn.prepareStatement(insertCartSql)) {
                pstmt.setString(1, itemName);
                pstmt.setInt(2, buyQty);
                pstmt.setString(3, size);
                pstmt.setString(4, weight);
                pstmt.setDouble(5, price);
                pstmt.setDouble(6, subtotal);
                pstmt.executeUpdate();
            }

            // B. MA-MINUS DAYON ANG QUANTITY SA INVENTORY DATABASE
            try (java.sql.PreparedStatement pstmtInv = conn.prepareStatement(updateInventorySql)) {
                pstmtInv.setInt(1, buyQty);
                pstmtInv.setString(2, itemName);
                pstmtInv.setString(3, size);
                pstmtInv.setString(4, weight);
                pstmtInv.setInt(5, buyQty); // Fixed: Added missing 5th parameter for quantity check
                pstmtInv.executeUpdate();
            }

            // C. MA-MINUS SAD SA AVAILABLE TABLE (KON NAA)
            try (java.sql.PreparedStatement pstmtAvail = conn.prepareStatement(updateAvailableSql)) {
                pstmtAvail.setInt(1, buyQty);
                pstmtAvail.setString(2, itemName);
                pstmtAvail.setString(3, size);
                pstmtAvail.setString(4, weight);
                pstmtAvail.setInt(5, buyQty);
                pstmtAvail.executeUpdate();
            }

            conn.commit(); // Save all changes atomically

            javax.swing.JOptionPane.showMessageDialog(this, buyQty + "x " + itemName + " (₱" + String.format("%.2f", subtotal) + ") has been added to the Cart and deducted from Inventory!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);

            // D. I-REFRESH ANG TABLE DISPLAY
            restoreItemToTable(null);

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error sa pag-add sa cart/inventory update: " + e.getMessage(), "Database Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this,"Please enter a valid quantity number.", "Format Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_cartactionPerformed

