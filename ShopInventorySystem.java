    private void btnReservedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReservedActionPerformed
        // TODO add your handling code here:
      jLabel3.setText("RESERVED ITEMS");
    highlightSidebarButton(btnReserved);

    table.setRowSorter(null);
    jPanel4.setVisible(true);

    if (table.getColumnCount() >= 8) {
        table.getColumnModel().getColumn(7).setHeaderValue("DATE RESERVED");
        table.getTableHeader().repaint();
    }

    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) table.getModel();
    model.setRowCount(0);

    String query = "SELECT * FROM inventory WHERE UPPER(status) = 'RESERVED'";

    try (java.sql.Connection conn = DBConnection.getConnection();
         java.sql.PreparedStatement pstmt = conn.prepareStatement(query);
         java.sql.ResultSet rs = pstmt.executeQuery()) {

        int counter = 1;
        while (rs.next()) {
            String dateVal = rs.getString("date_sold");

            if (dateVal == null || dateVal.trim().isEmpty()) {
                dateVal = java.time.LocalDate.now().toString();
            } else if (dateVal.length() >= 10) {
                dateVal = dateVal.substring(0, 10);
            }

            Object[] row = new Object[] {
                counter++,
                rs.getString("item_name"),
                rs.getInt("quantity"),
                rs.getString("size") != null ? rs.getString("size") : "-",
                rs.getString("weight") != null ? rs.getString("weight") : "-",
                "₱" + String.format("%.2f", rs.getDouble("price")),
                rs.getString("status"),
                dateVal
            };
            model.addRow(row);
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error loading Reserved items: " + e.getMessage(), "Database Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnReservedActionPerformed

