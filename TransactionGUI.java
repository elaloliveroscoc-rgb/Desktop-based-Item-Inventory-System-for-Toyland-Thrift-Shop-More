public void loadTransactionTableWithFilter(String filterType) {
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tableTransaction.getModel();
    model.setRowCount(0);

    String query = "SELECT * FROM sales_transactions ";

    // Filter Logic base sa napili sa user
    switch (filterType) {
        case "Daily":
            query += "WHERE DATE(transaction_date) = CURDATE() ";
            break;
        case "Weekly":
            query += "WHERE YEARWEEK(transaction_date, 1) = YEARWEEK(CURDATE(), 1) ";
            break;
        case "Monthly":
            query += "WHERE MONTH(transaction_date) = MONTH(CURDATE()) AND YEAR(transaction_date) = YEAR(CURDATE()) ";
            break;
        default: // "All"
            break;
    }

    query += "ORDER BY transaction_id DESC";

    try (java.sql.Connection conn = none.shopinventorysystem.DBConnection.getConnection();
         java.sql.PreparedStatement pstmt = conn.prepareStatement(query);
         java.sql.ResultSet rs = pstmt.executeQuery()) {

        int counter = 1;
        double totalSales = 0.0;

        while (rs.next()) {
            double amount = rs.getDouble("total_amount");
            totalSales += amount;

            Object[] row = new Object[] {
                counter++,
                rs.getString("customer_name"),
                rs.getString("item_name"),
                rs.getInt("quantity"),
                "₱" + String.format("%.2f", amount),
                "₱" + String.format("%.2f", rs.getDouble("amount_paid")),
                "₱" + String.format("%.2f", rs.getDouble("change_amount")),
                rs.getString("transaction_date")
            };
            model.addRow(row);
        }

        // I-update ang Total Sales Label (kon naa)
        if (lblTotalSales != null) {
            lblTotalSales.setText("Total Sales (" + filterType + "): ₱" + String.format("%.2f", totalSales));
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error loading transactions: " + e.getMessage(), "Database Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
}

